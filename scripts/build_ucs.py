"""Build the pure-constant UCS module from the authoritative 753-row TSV.

The TSV is copied from the ucs-sound-naming skill and is the only data source.
Run: python scripts/build_ucs.py
"""

from __future__ import annotations

import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TSV = ROOT / "docs" / "UCS分类表-8.2.1.tsv"
OUT = ROOT / "src" / "ucs_namer" / "ucs_data.py"


def main() -> None:
    with TSV.open("r", encoding="utf-8", newline="") as handle:
        rows = list(csv.reader(handle, delimiter="\t"))
    if not rows or rows[0][:4] != ["Category", "SubCategory", "CatID", "CatShort"]:
        raise SystemExit("UCS TSV header does not match the expected layout")
    body = [row for row in rows[1:] if row and any(cell.strip() for cell in row)]
    if len(body) != 753:
        raise SystemExit(f"expected 753 UCS rows, got {len(body)}")
    ids = [row[2] for row in body]
    if len(set(ids)) != len(ids):
        raise SystemExit("duplicate CatID in UCS TSV")

    lines = [
        '"""UCS 8.2.1 categories. Generated by scripts/build_ucs.py; do not edit."""',
        "",
        "from __future__ import annotations",
        "",
        "# (CatID, Category, SubCategory, Category_zh, SubCategory_zh, Synonyms_zh)",
        "CATEGORIES = (",
    ]
    for row in body:
        category, subcategory, cat_id, _cat_short, category_zh, subcategory_zh, synonyms = row[:7]
        lines.append(
            "    ("
            + ", ".join(
                repr(value)
                for value in (cat_id, category, subcategory, category_zh, subcategory_zh, synonyms)
            )
            + "),"
        )
    lines.append(")")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} with {len(body)} categories")


if __name__ == "__main__":
    main()
